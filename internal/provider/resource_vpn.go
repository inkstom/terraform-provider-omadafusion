	resp.Diagnostics.Append(req.Config.Get(ctx, &m)...)
	if resp.Diagnostics.HasError() {
		return
	}
	if v := m.Service; !v.IsNull() && !v.IsUnknown() {
		if _, ok := ddnsServices[v.ValueString()]; !ok {
			resp.Diagnostics.AddAttributeError(path.Root("service"), "Invalid service", "must be dyndns, noip, peanuthull or comexe")
		}
	}
	if v := m.UpdateInterval; !v.IsNull() && !v.IsUnknown() && v.ValueInt64() < 1 {
		resp.Diagnostics.AddAttributeError(path.Root("update_interval"), "Invalid interval", "must be at least 1 minute")
	}
