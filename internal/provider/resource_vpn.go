// ======================= WireGuard interface =======================

var (
	_ resource.ResourceWithImportState    = &wireguardResource{}
	_ resource.ResourceWithValidateConfig = &wireguardResource{}
)

func newWireGuardResource() resource.Resource { return &wireguardResource{} }

type wireguardResource struct{ data *providerData }

type wireguardModel struct {
	ID         types.String `tfsdk:"id"`
	Site       types.String `tfsdk:"site"`
	Name       types.String `tfsdk:"name"`
	Enabled    types.Bool   `tfsdk:"enabled"`
	ListenPort types.Int64  `tfsdk:"listen_port"`
	MTU        types.Int64  `tfsdk:"mtu"`
	LocalIP    types.String `tfsdk:"local_ip"`
	PrivateKey types.String `tfsdk:"private_key"`
	PublicKey  types.String `tfsdk:"public_key"`
}

func (r *wireguardResource) Metadata(_ context.Context, req resource.MetadataRequest, resp *resource.MetadataResponse) {
	resp.TypeName = req.ProviderTypeName + "_wireguard"
}

func (r *wireguardResource) Schema(_ context.Context, _ resource.SchemaRequest, resp *resource.SchemaResponse) {
	resp.Schema = schema.Schema{
		Description: "A WireGuard VPN interface on the gateway (VPN > WireGuard). Add peers with `omadafusion_wireguard_peer`. " +
			"When `private_key` is omitted the controller generates a key pair; the private key is stored in state.",
		Attributes: map[string]schema.Attribute{
			"id":          idAttribute("Interface ID."),
			"site":        siteAttribute(),
			"name":        schema.StringAttribute{Required: true, Description: "Interface name. Must be unique."},
			"enabled":     schema.BoolAttribute{Optional: true, Computed: true, Default: booldefault.StaticBool(true), Description: "Whether the interface is up."},
			"listen_port": schema.Int64Attribute{Required: true, Description: "UDP listen port on the WAN, 1-65535."},
			"mtu":         schema.Int64Attribute{Optional: true, Computed: true, Default: int64default.StaticInt64(1420), Description: "Interface MTU, 576-1440."},
			"local_ip":    schema.StringAttribute{Required: true, Description: "Tunnel address of the gateway, e.g. `10.250.0.1`."},
			"private_key": schema.StringAttribute{
				Optional: true, Computed: true, Sensitive: true,
				Description:   "Base64 private key. Generated by the controller when omitted.",
				PlanModifiers: []planmodifier.String{stringplanmodifier.UseStateForUnknown()},
			},
			"public_key": schema.StringAttribute{
				Computed: true, Description: "Public key to give to peers.",
				PlanModifiers: []planmodifier.String{stringplanmodifier.UseStateForUnknown()},
			},
		},
	}
}

func (r *wireguardResource) Configure(_ context.Context, req resource.ConfigureRequest, resp *resource.ConfigureResponse) {
	r.data = configureData(req.ProviderData, &resp.Diagnostics)
}

func (r *wireguardResource) ValidateConfig(ctx context.Context, req resource.ValidateConfigRequest, resp *resource.ValidateConfigResponse) {
	var m wireguardModel
	resp.Diagnostics.Append(req.Config.Get(ctx, &m)...)
	if resp.Diagnostics.HasError() {
		return
	}
	if v := m.ListenPort; !v.IsNull() && !v.IsUnknown() && (v.ValueInt64() < 1 || v.ValueInt64() > 65535) {
		resp.Diagnostics.AddAttributeError(path.Root("listen_port"), "Invalid port", "must be 1-65535")
	}
	if v := m.MTU; !v.IsNull() && !v.IsUnknown() && (v.ValueInt64() < 576 || v.ValueInt64() > 1440) {
		resp.Diagnostics.AddAttributeError(path.Root("mtu"), "Invalid MTU", "must be 576-1440")
	}
	if v := m.LocalIP; !v.IsNull() && !v.IsUnknown() && net.ParseIP(v.ValueString()).To4() == nil {
		resp.Diagnostics.AddAttributeError(path.Root("local_ip"), "Invalid address", "must be an IPv4 address")
	}
}

func (m *wireguardModel) toAPI() client.WireGuard {
	return client.WireGuard{
		Name: m.Name.ValueString(), Status: m.Enabled.ValueBool(), MTU: int(m.MTU.ValueInt64()),
		ListenPort: int(m.ListenPort.ValueInt64()), PrivateKey: m.PrivateKey.ValueString(), LocalIP: m.LocalIP.ValueString(),
	}
}

func (m *wireguardModel) fromAPI(w *client.WireGuard) {
	m.ID = types.StringValue(w.ID)
	m.Name = types.StringValue(w.Name)
	m.Enabled = types.BoolValue(w.Status)
	m.MTU = types.Int64Value(int64(w.MTU))
	m.ListenPort = types.Int64Value(int64(w.ListenPort))
	m.LocalIP = types.StringValue(w.LocalIP)
	m.PrivateKey = types.StringValue(w.PrivateKey)
	m.PublicKey = types.StringValue(w.PublicKey)
}

func (r *wireguardResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var plan wireguardModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	siteID, ok := r.data.mustSite(ctx, plan.Site, &resp.Diagnostics)
	if !ok || resp.Diagnostics.HasError() {
		return
	}
	if plan.PrivateKey.IsNull() || plan.PrivateKey.IsUnknown() || plan.PrivateKey.ValueString() == "" {
		kp, err := r.data.client.GenerateWireGuardKey(ctx, siteID)
		if err != nil {
			apiError(&resp.Diagnostics, "generating WireGuard key", err)
			return
		}
		plan.PrivateKey = types.StringValue(kp.PrivateKey)
	}
	id, err := r.data.client.CreateWireGuard(ctx, siteID, plan.toAPI())
	if err != nil {
		apiError(&resp.Diagnostics, "creating WireGuard interface", err)
		return
	}
	w, err := r.data.client.WireGuard(ctx, siteID, id)
	if err != nil {
		apiError(&resp.Diagnostics, "reading back WireGuard interface", err)
		return
	}
	plan.fromAPI(w)
	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
}

func (r *wireguardResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	var state wireguardModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	siteID, ok := r.data.mustSite(ctx, state.Site, &resp.Diagnostics)
	if !ok || resp.Diagnostics.HasError() {
		return
	}
	w, err := r.data.client.WireGuard(ctx, siteID, state.ID.ValueString())
	if handleReadErr(ctx, err, resp, "WireGuard interface") {
		return
	}
	state.fromAPI(w)
	resp.Diagnostics.Append(resp.State.Set(ctx, &state)...)
}

func (r *wireguardResource) Update(ctx context.Context, req resource.UpdateRequest, resp *resource.UpdateResponse) {
	var plan, state wireguardModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	siteID, ok := r.data.mustSite(ctx, plan.Site, &resp.Diagnostics)
	if !ok || resp.Diagnostics.HasError() {
		return
	}
	if plan.PrivateKey.IsUnknown() || plan.PrivateKey.ValueString() == "" {
		plan.PrivateKey = state.PrivateKey
	}
	id := state.ID.ValueString()
	if err := r.data.client.UpdateWireGuard(ctx, siteID, id, plan.toAPI()); err != nil {
		apiError(&resp.Diagnostics, "updating WireGuard interface", err)
		return
	}
	w, err := r.data.client.WireGuard(ctx, siteID, id)
	if err != nil {
		apiError(&resp.Diagnostics, "reading back WireGuard interface", err)
		return
	}
	plan.fromAPI(w)
	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
}

func (r *wireguardResource) Delete(ctx context.Context, req resource.DeleteRequest, resp *resource.DeleteResponse) {
	var state wireguardModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	siteID, ok := r.data.mustSite(ctx, state.Site, &resp.Diagnostics)
	if !ok {
		return
	}
	if err := r.data.client.DeleteWireGuard(ctx, siteID, state.ID.ValueString()); err != nil && !client.IsNotFound(err) {
		apiError(&resp.Diagnostics, "deleting WireGuard interface", err)
	}
}

func (r *wireguardResource) ImportState(ctx context.Context, req resource.ImportStateRequest, resp *resource.ImportStateResponse) {
	importSiteAndID(ctx, req, resp, "id")
}

