func (r *wireguardPeerResource) Schema(_ context.Context, _ resource.SchemaRequest, resp *resource.SchemaResponse) {
	resp.Schema = schema.Schema{
		Description: "A peer of a WireGuard interface (VPN > WireGuard > Peers). For a remote-access client, set " +
			"`allowed_addresses` to the client's tunnel address and leave `endpoint` empty.",
		Attributes: map[string]schema.Attribute{
			"id":      idAttribute("Peer ID."),
			"site":    siteAttribute(),
			"name":    schema.StringAttribute{Required: true, Description: "Peer name. Must be unique."},
			"enabled": schema.BoolAttribute{Optional: true, Computed: true, Default: booldefault.StaticBool(true), Description: "Whether the peer is active."},
			"interface_id": schema.StringAttribute{
				Required: true, Description: "ID of the `omadafusion_wireguard` interface.",
				PlanModifiers: []planmodifier.String{stringplanmodifier.RequiresReplace()},
			},
			"public_key": schema.StringAttribute{Required: true, Description: "The peer's base64 public key."},
			"allowed_addresses": schema.ListAttribute{
				Required: true, ElementType: types.StringType, Description: "Addresses routed to this peer, in CIDR form.",
			},
			"endpoint":      schema.StringAttribute{Optional: true, Computed: true, Default: stringdefault.StaticString(""), Description: "Peer host or IP. Empty for roaming clients."},
			"endpoint_port": schema.Int64Attribute{Optional: true, Description: "Peer UDP port. Only with `endpoint`."},
			"preshared_key": schema.StringAttribute{Optional: true, Computed: true, Sensitive: true, Default: stringdefault.StaticString(""), Description: "Optional base64 preshared key."},
			"keepalive":     schema.Int64Attribute{Optional: true, Computed: true, Default: int64default.StaticInt64(25), Description: "Persistent keepalive in seconds, 0 to disable."},
			"comment":       schema.StringAttribute{Optional: true, Computed: true, Default: stringdefault.StaticString(""), Description: "Free-form comment."},
		},
	}
}

func (r *wireguardPeerResource) Configure(_ context.Context, req resource.ConfigureRequest, resp *resource.ConfigureResponse) {
	r.data = configureData(req.ProviderData, &resp.Diagnostics)
}

func (r *wireguardPeerResource) ValidateConfig(ctx context.Context, req resource.ValidateConfigRequest, resp *resource.ValidateConfigResponse) {
	var m wireguardPeerModel
	resp.Diagnostics.Append(req.Config.Get(ctx, &m)...)
	if resp.Diagnostics.HasError() {
		return
	}
	if !m.AllowedAddresses.IsNull() && !m.AllowedAddresses.IsUnknown() {
		as, allKnown := knownElements(m.AllowedAddresses.Elements())
		if allKnown && len(as) == 0 {
			resp.Diagnostics.AddAttributeError(path.Root("allowed_addresses"), "No addresses", "set at least one address")
		}
		for _, a := range as {
			if _, _, err := net.ParseCIDR(a); err != nil {
				resp.Diagnostics.AddAttributeError(path.Root("allowed_addresses"), "Invalid CIDR", fmt.Sprintf("%q is not a CIDR", a))
			}
		}
	}
	if v := m.EndpointPort; !v.IsNull() && !v.IsUnknown() && (v.ValueInt64() < 1 || v.ValueInt64() > 65535) {
		resp.Diagnostics.AddAttributeError(path.Root("endpoint_port"), "Invalid port", "must be 1-65535")
	}
	if v := m.KeepAlive; !v.IsNull() && !v.IsUnknown() && (v.ValueInt64() < 0 || v.ValueInt64() > 65535) {
		resp.Diagnostics.AddAttributeError(path.Root("keepalive"), "Invalid keepalive", "must be 0-65535")
	}
}

func (m *wireguardPeerModel) toAPI(ctx context.Context, diags *diag.Diagnostics) client.WireGuardPeer {
	p := client.WireGuardPeer{
		Name: m.Name.ValueString(), Status: m.Enabled.ValueBool(), InterfaceID: m.InterfaceID.ValueString(),
		PublicKey: m.PublicKey.ValueString(), AllowAddress: listToStrings(ctx, m.AllowedAddresses, diags),
		Endpoint: m.Endpoint.ValueString(), PresharedKey: m.PresharedKey.ValueString(),
		KeepAlive: int(m.KeepAlive.ValueInt64()), Comment: m.Comment.ValueString(),
	}
	if !m.EndpointPort.IsNull() && !m.EndpointPort.IsUnknown() {
		v := int(m.EndpointPort.ValueInt64())
		p.EndpointPort = &v
	}
	return p
}

func (m *wireguardPeerModel) fromAPI(ctx context.Context, p *client.WireGuardPeer, diags *diag.Diagnostics) {
	m.ID = types.StringValue(p.ID)
	m.Name = types.StringValue(p.Name)
	m.Enabled = types.BoolValue(p.Status)
	m.InterfaceID = types.StringValue(p.InterfaceID)
	m.PublicKey = types.StringValue(p.PublicKey)
	m.AllowedAddresses = stringsToList(ctx, p.AllowAddress, diags)
	m.Endpoint = types.StringValue(p.Endpoint)
	if p.EndpointPort != nil && *p.EndpointPort != 0 {
		m.EndpointPort = types.Int64Value(int64(*p.EndpointPort))
	} else {
		m.EndpointPort = types.Int64Null()
	}
	m.PresharedKey = types.StringValue(p.PresharedKey)
	m.KeepAlive = types.Int64Value(int64(p.KeepAlive))
	m.Comment = types.StringValue(p.Comment)
}

