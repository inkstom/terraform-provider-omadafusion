func (m *ddnsModel) toAPI() client.DDNS {
	return client.DDNS{
		Service: ddnsServices[m.Service.ValueString()], WANPortID: m.WANPortID.ValueString(), Username: m.Username.ValueString(),
		Password: m.Password.ValueString(), Domain: m.Domain.ValueString(), UpdateInterval: int(m.UpdateInterval.ValueInt64()),
		Status: m.Enabled.ValueBool(),
	}
}

func (m *ddnsModel) fromAPI(d *client.DDNS) {
	m.ID = types.StringValue(d.ID)
	m.Service = types.StringValue(fmt.Sprint(d.Service))
	for k, v := range ddnsServices {
		if v == d.Service {
			m.Service = types.StringValue(k)
		}
	}
	m.WANPortID = types.StringValue(d.WANPortID)
	m.Username = types.StringValue(d.Username)
	m.Password = types.StringValue(d.Password)
	m.Domain = types.StringValue(d.Domain)
	m.UpdateInterval = types.Int64Value(int64(d.UpdateInterval))
	m.Enabled = types.BoolValue(d.Status)
}

